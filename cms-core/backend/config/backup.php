<?php

/**
 * E5 — پشتیبان‌گیری دیتابیس با `pg_dump`.
 *
 * ## چرا `DATABASE_URL` و نه تکه‌تکه کردن کانفیگ؟
 *
 * `pg_dump` یک ابزار بیرونی است و فقط یک رشتهٔ اتصال را می‌فهمد. اگر هر تکه را
 * جدا بدهیم، باید دوباره سرِ `sslmode`/`options` را حدس بزنیم و هر چیزی که در
 * `config/database.php` هست و اینجا نیست، بی‌صدا از قلم می‌افتد. یک URL یعنی
 * **همان رشته‌ای که خود برنامه با آن وصل می‌شود** — پس بکاپ و برنامه نمی‌توانند
 * به دو دیتابیس مختلف وصل شوند.
 *
 * ## چرا fail-closed؟
 *
 * اگر `DATABASE_URL` نباشد، **هیچ** فایلی نوشته نمی‌شود و فرمان FAILURE می‌دهد.
 * بکاپی که «ساخته شد ولی از دیتابیس خالی است» بدتر از نبودن بکاپ است، چون مدیر
 * تا روز حادثه فکر می‌کند همه‌چیز امن است.
 */
return [

    /**
     * رشتهٔ اتصال. نمونه: `postgres://cms:secret@db:5432/cms?sslmode=disable`
     * خالی یعنی بکاپ غیرفعال — و `backup:run` با پیام فارسی FAILURE می‌دهد.
     */
    'database_url' => env('DATABASE_URL'),

    /** مسیر باینری `pg_dump`. اگر در PATH نیست، مسیر کامل بدهید. */
    'binary' => env('BACKUP_PG_DUMP', 'pg_dump'),

    /** null = `storage/app/backups`. مسیر دلخواه برای نصب روی دیسک جدا. */
    'path' => env('BACKUP_PATH'),

    /** چند نسخهٔ آخر روی دیسک بماند (چرخش). */
    'keep' => (int) env('BACKUP_KEEP', 7),

    /** سقف ثانیه‌ای اجرای `pg_dump` — یک dump بی‌پایان نباید worker را قفل کند. */
    'timeout' => (int) env('BACKUP_TIMEOUT', 600),

    /** نام فایل مانیفست داخل همان پوشه. */
    'manifest' => 'manifest.json',

];
