<?php

/**
 * پیکربندیِ منبعِ وضعیتِ اشتراک (تسک J2).
 *
 * ## این فایل دقیقاً چه تصمیمی می‌گیرد؟
 *
 * یک سؤال: **دادهٔ اشتراک از کجا می‌آید؟** سه حالت، و فقط یکی برقرار است:
 *
 *  ۱. `remote_url` خالی ← داده در همین دیتابیس است، از راهِ بستهٔ `subscription`.
 *     حالتِ عادیِ مشتری.
 *  ۲. `remote_url` پر ← مرکزی در یک استقرارِ دیگر است (J4) و این نصب از راهِ
 *     HTTP وضعیت می‌پرسد. جدول‌های اشتراک اینجا لازم نیست.
 *  ۳. بسته نبود ← `NullSubscriptionResolver`، یعنی «قابلیتِ مرکزی نصب نیست».
 *
 * ## چرا این تنظیمات **fail-closed** هستند
 *
 * هر مقداری که اینجا اشتباه پر شود، به یکی از این دو می‌رسد:
 * سایتِ مشتری از پنل بیرون می‌افتد، یا یک نصبِ local بی‌سروصدا به جدولِ local
 * می‌چسبد و با دادهٔ کهنه جواب می‌دهد.
 *
 * برای همین:
 *  - `remote_url` پیش‌فرض **null** است (نه رشتهٔ خالی، نه آدرسِ ساختگی) — یعنی
 *    تا وقتی کسی آدرسی ننوشته، اصلاً مسیرِ دور فعال نمی‌شود.
 *  - `remote_timeout` کوتاه است، چون این مسیر در رندرِ صفحه صدا زده می‌شود.
 *  - `remote_token` لازم نیست که باشد؛ اگر نباشد، درخواست بی‌توکن می‌رود و
 *    مرکزی ۴۰۱ می‌دهد که resolver آن را مثل هر خطای دیگری می‌بلعد.
 */

return [

    /**
     * J12 — کلاسِ پیاده‌سازیِ resolver. پیش‌فرض **خالی** = `NullSubscriptionResolver`.
     *
     * چرا روی binding است و نه یک شرطِ `remote_url` در هسته: نسخهٔ رایگان نباید
     * هیچ مسیرِ کدِ اشتراکِ دور داشته باشد. با این کلید، هسته هیچ نامِ کلاسی را
     * هارد-کد نمی‌کند و روشن‌کردنِ resolverِ واقعی یک تصمیمِ پیکربندی است.
     *
     * نمونه‌ها (پس از بازگردانی از `plugins/_quarantine/`):
     *   SUBSCRIPTION_RESOLVER="App\Services\Subscription\PluginSubscriptionResolver"
     *   SUBSCRIPTION_RESOLVER="App\Services\Subscription\RemoteSubscriptionResolver"
     */
    'resolver' => env('SUBSCRIPTION_RESOLVER'),

    /**
     * J2 — آدرسِ پایهٔ مرکزیِ دور. `null` یا خالی = حالتِ محلی.
     *
     * ⚠️ پس از J12 پیاده‌سازیِ دور در `plugins/_quarantine/core-subscription/`
     * است. این کلید فقط وقتی معنا دارد که `resolver` به همان کلاس برگردد.
     *
     * ⚠️ **پروتکل را کامل بنویسید** (`https://…`). اگر بدونِ پروتکل باشد، HTTPِ
     * لاراول آن را نمی‌فهمد و هر فراخوانی exception می‌دهد — که یعنی همیشه
     * «نمی‌دانیم» و بازار خراب می‌شود.
     */
    'remote_url' => env('SUBSCRIPTION_REMOTE_URL'),

    /**
     * مهلتِ HTTP، ثانیه. پیش‌فرض ۳ و **عمداً** کم.
     *
     * رندرِ صفحه نباید منتظرِ یک مرکزیِ پایین بماند؛ بهتر است زود به حالتِ عمومی
     * برسد. اگر مرکزی واقعاً کند است، این عدد را بالا ببرید نه اینکه
     * `timeout` را خاموش کنید.
     */
    'remote_timeout' => (int) env('SUBSCRIPTION_REMOTE_TIMEOUT', 3),

    /**
     * توکنِ دسترسی به مرکزی. اختیاری.
     *
     * اگر مرکزی عمومی باشد، خالی می‌ماند و وضعیتِ عمومی (فعال/تعلیق) بدون توکن
     * خوانده می‌شود — که برای `/api/v1/site/status` کافی است.
     */
    'remote_token' => env('SUBSCRIPTION_REMOTE_TOKEN'),
];