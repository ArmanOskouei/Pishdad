<?php

/*
|--------------------------------------------------------------------------
| تنظیمات کانال پیامک (E3)
|--------------------------------------------------------------------------
|
| کانال پیامک **جدا از ایمیل** است و عمداً درایور خودش را دارد، چون هیچ
| provider استانداردی پشت Laravel نیست و «یک provider دیگر» که فقط برای
| پیامک انتخاب می‌شود.
|
| درایورها:
|   null   (پیش‌فرض) — هیچ پیامکی بیرون نمی‌رود. تنها حالتِ «صادقانه» تا وقتی
|          کلیدهای واقعی نداریم. `ProfileController::smsRequest` هم دقیقاً همین
|          را به کاربر می‌گوید (`sms.not_configured`) و وانمود نمی‌کند ارسال شد.
|   log    — فقط در لاگ نوشته می‌شود؛ هیچ‌کس گوشی‌اش روشن نمی‌شود. برای تست.
|   panel  — درگاهِ واقعی. نیازمند `SMS_PANEL_*` (پایین).
|
| ⭐ قاعدهٔ fail-closed: اگر `SMS_DRIVER=panel` باشد ولی یکی از کلیدهای
| لازم خالی باشد، `SmsDriverFactory` ** exception می‌دهد ** و پیامش فارسی و
| نامِ دقیق کلیدِ جاافتاده را می‌گوید. عمداً «پیام بفرست و بی‌خبر رد شو» نداریم:
| کاربرِ نهایی باید بداند کدش نرسیده است.
|
*/

return [

    /*
    | درایور فعال. پیش‌فرض `null` یعنی «پیامک نداریم» — نه خطا، ولی نه هم فریب.
    */
    'driver' => env('SMS_DRIVER', 'null'),

    /*
    | درگاهِ واقعی (E3). تا وقتی این‌ها خالی‌اند، `SMS_DRIVER=panel` خطا می‌دهد.
    */
    'panel' => [
        'url' => env('SMS_PANEL_URL'),
        'api_key' => env('SMS_PANEL_API_KEY'),
        'sender' => env('SMS_PANEL_SENDER'),
    ],

    /*
    | سقفِ زمانِ تماس تا worker روی درگاهِ مرده قفل نشود (هم‌ارز `MAIL_TIMEOUT`).
    */
    'timeout' => (int) env('SMS_TIMEOUT', 10),

    /*
    | شمارهٔ فرستندهٔ پیش‌فرض برای پیامک‌های تراکنشی (اگر بلوک/اعلان آن را ندهد).
    */
    'default_sender' => env('SMS_DEFAULT_SENDER'),

];