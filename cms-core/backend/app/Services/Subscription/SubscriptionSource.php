<?php

declare(strict_types=1);

namespace App\Services\Subscription;

/**
 * K7.2 — رابطِ وضعیت اشتراک، و منبعِ پیش‌فرضِ آن.
 *
 * ## چرا این رابط وجود دارد
 *
 * `ClientSubscriptionResolver` قبلاً مستقیم کلاس‌های مدلِ افزونهٔ مرکزی را صدا
 * می‌زد. یعنی **هسته به افزونهٔ مرکزی وابسته بود** — و آن افزونه قرار است
 * خصوصی باشد و در انتشارِ عمومی نباشد. یعنی نصبِ تازهٔ مشتری ۵۰۰ می‌داد. این را
 * با شبیه‌سازیِ واقعی دیدم، نه با حدس:
 *
 * ```
 * /api/v1/site/status  →  500
 *   Class "…\Central\Models\Subscription" not found
 *   app/Services/Subscription/ClientSubscriptionResolver.php:54
 * ```
 *
 * پس راه درست این نیست که `null` برگردانیم و امید داشته باشیم کسی نپرسد.
 * راه درست این است که هسته **یک رابط** بشناسد و افزونه آن را پیاده کند.
 *
 * ## چرا این فایل در `KNOWN_VIOLATIONS` نیست
 *
 * چون نامِ `Pishdad\Plugins\Central` فقط در **متنِ توضیحی** این فایل می‌آید،
 * نه در کد. نگهبان `CentralBoundaryTest` متن را می‌خواند، پس اسم را می‌بیند؛ ولی
 * یک interface بدون هیچ وابستگیِ اجرایی، وابستگی نیست. اگر روزی این فایل
 * `use` اضافه کند، نگهبان قرمز می‌شود — که همان چیزی است که می‌خواهیم.
 *
 * ## قرارداد
 *
 * `status()` فقط دو چیز برمی‌گرداند و هیچ چیز دیگری:
 *  - `active` یا `suspended`
 *  - پیامی که به بازدیدکننده نشان داده می‌شود
 *
 * عمداً کم است. هر چیزی بیشتر (فاکتور، پلن، مبلغ) یعنی هسته دوباره به مدلِ
 * مرکزی چنگ می‌زند و به همین ترتیب دوباره می‌شکند.
 */
interface SubscriptionSource
{
    /**
     * @param  int|null  $ownerUserId  صاحبِ سایت، اگر شناخته شود
     * @return array{status: string, message: string}|null
     *                                                     `null` یعنی «این منبع دربارهٔ این سایت چیزی نمی‌داند» — که با
     *                                                     «معلق است» فرق دارد و نباید یکی شوند.
     */
    public function status(?int $ownerUserId = null): ?array;
}
