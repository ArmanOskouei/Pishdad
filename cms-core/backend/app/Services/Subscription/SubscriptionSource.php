<?php

declare(strict_types=1);

namespace App\Services\Subscription;

/**
 * K7.2 — رابطِ وضعیت اشتراک، و منبعِ پیش‌فرضِ آن.
 *
 * ## چرا این رابط وجود دارد
 *
 * `ClientSubscriptionResolver` قبلاً مستقیم کلاس‌های مدلِ افزونهٔ مرکزی را صدا
 * می‌زد. یعنی **هسته به افزونهٔ مرکزی وابسته بود** — و آن افزونه قرار است
 * خصوصی باشد و در انتشارِ عمومی نباشد. یعنی نصبِ تازهٔ مشتری ۵۰۰ می‌داد. این را
 * با شبیه‌سازیِ واقعی دیدم، نه با حدس:
 *
 * ```
 * /api/v1/site/status  →  500
 *   Class "…\Central\Models\Subscription" not found
 *   app/Services/Subscription/ClientSubscriptionResolver.php:54
 * ```
 *
 * پس راه درست این نیست که `null` برگردانیم و امید داشته باشیم کسی نپرسد.
 * راه درست این است که هسته **یک رابط** بشناسد و افزونه آن را پیاده کند.
 *
 * ## چرا این فایل در `KNOWN_VIOLATIONS` نیست
 *
 * چون نامِ `Pishdad\Plugins\Central` فقط در **متنِ توضیحی** این فایل می‌آید،
 * نه در کد. نگهبان `CentralBoundaryTest` متن را می‌خواند، پس اسم را می‌بیند؛ ولی
 * یک interface بدون هیچ وابستگیِ اجرایی، وابستگی نیست. اگر روزی این فایل
 * `use` اضافه کند، نگهبان قرمز می‌شود — که همان چیزی است که می‌خواهیم.
 *
 * ## قرارداد
 *
 * `status()` فقط دو چیز برمی‌گرداند و هیچ چیز دیگری:
 *  - `active` یا `suspended`
 *  - پیامی که به بازدیدکننده نشان داده می‌شود
 *
 * عمداً کم است. هر چیزی بیشتر (فاکتور، پلن، مبلغ) یعنی هسته دوباره به مدلِ
 * مرکزی چنگ می‌زند و به همین ترتیب دوباره می‌شکند.
 */
interface SubscriptionSource
{
    /**
     * @param  int|null  $ownerUserId  صاحبِ سایت، اگر شناخته شود
     * @return array{status: string, message: string}|null
     *                                                     `null` یعنی «این منبع دربارهٔ این سایت چیزی نمی‌داند» — که با
     *                                                     «معلق است» فرق دارد و نباید یکی شوند.
     */
    public function status(?int $ownerUserId = null): ?array;

    /**
     * J5 — وضعیتِ **یک سایتِ مشخص**، نه یک کاربر.
     *
     * ## چرا این متد تازه لازم شد
     *
     * `ClientSubscriptionResolver::forSiteId()` می‌پرسد «نصبِ این `site_id` در چه
     * وضعیتی است؟». ولی `status()` فقط یک **شناسهٔ کاربر** می‌گیرد، نه شناسهٔ سایت.
     *
     * یعنی رابط نمی‌توانست به سؤالی که هسته می‌پرسد جواب بدهد — و تنها راهِ دور زدنش
     * همان چیزی بود که J5 برداشت: کوئریِ مستقیمِ هسته روی جدولِ افزونه.
     *
     * ## فرقش با `status()`
     *
     *  - `status()` — «اشتراکِ *این کاربر* چیست؟» (داشبورد، `forUser`)
     *  - `statusForSite()` — «اشتراکِ *این سایت* چیست؟» (`/site/status`)
     *
     * این دو می‌توانند جوابِ متفاوت بدهند: یک کاربر ممکن است چند سایت داشته باشد، و
     * یک سایت بی‌ صاحب باشد. یکی را از دیگری ساختن، یکی از این دو را می‌شکند.
     *
     * @param  string|null  $siteId  `null` یعنی «نصبِ پیش‌فرض/تنها».
     * @return array{status: string, message: string}|null
     *                                                      `null` یعنی «این سایت رکوردی ندارد».
     */
    public function statusForSite(?string $siteId = null): ?array;

    /**
     * J5 — کارتِ اشتراک برای **یک کاربر**، در یک آرایه.
     *
     * ## چرا این متد لازم شد
     *
     * `DashboardController` (کارت + هشدارها) و `MediaController` (سهمیه) هر دو به
     * `tier` و `status` و سررسید نیاز داشتند. پیش از J5 هر دو مستقیم مدل‌های
     * افزونه را صدا می‌زدند.
     *
     * مسیرِ جایگزین (`SubscriptionResolver`) کار می‌کرد ولی **دو انبارِ داده** را
     * به هم وصل می‌کرد: افزونهٔ اشتراک جدول‌های `subscription_*` خودش را دارد،
     * در حالی که این مسیر از `central_*` می‌خواند. نتیجه این بود که داشبورد در
     * محیطی که آن جدول‌ها مهاجرت نرفته بودند، بی‌صدا `null` می‌داد.
     *
     * این متد مسیر را **یکی** می‌کند: هر بسته‌ای که دادهٔ اشتراک دارد، کلِ کارت را
     * یک‌جا می‌دهد و خودش تصمیم می‌گیرد چه چیزی «ندارد» یعنی.
     *
     * ## چرا آرایه، نه مدل
     *
     * مدل یعنی هسته می‌داند ستون‌های `tier` و `due_at` وجود دارند. آرایه یعنی هر
     * افزونه شکلِ خودش را می‌دهد و هسته فقط کلیدهایی را می‌خواند که همین قرارداد
     * گذاشته — و اگر افزونه کلیدی را نداشت، `null` می‌گیرد نه خطا.
     *
     * ⚠️ افزونهٔ صاحبِ داده مجاز است **رکورد بسازد** (مثلاً مشتریِ تازه)، چون
     * نوشتن روی جدولِ خودش کارِ خودش است. هسته هرگز این کار را نمی‌کند.
     *
     * @param  int|null  $ownerUserId  `null` یعنی «بدون مالک» (سوپرادمین).
     * @return array{
     *     tier: string|null,
     *     status: string|null,
     *     due_at: string|null,
     *     days_remaining: int|null,
     *     overdue_invoice_count: int,
     *     is_due_soon: bool
     * }|null  `null` یعنی «این قابلیت برای این کاربر نیست».
     */
    public function forUser(?int $ownerUserId): ?array;
}
