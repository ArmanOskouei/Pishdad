/**
 * E78 — زمان‌بندیِ واحدِ جستجوی زنده (سایت + پنل).
 *
 * مشکل: هر حرف یک ریکوئست می‌زد (دراپ‌داونِ ادمین با دبونسِ ۱۵۰ms از حرفِ
 * اول، سایت با ۲۰۰ms از حرفِ دوم) — چهار عددِ جدا در چهار فایل که هیچ‌کدام
 * با هم هم‌خوان نبودند.
 *
 * چرا ۳ حرف و ۳۰۰ میلی‌ثانیه:
 *  - حداقلِ طول (۳) دستورِ صریحِ کاربر است؛ کوئریِ ۱–۲ حرفی عملاً همیشه
 *    هزاران نتیجهٔ بی‌ربط می‌دهد و فقط بارِ سرور است.
 *  - دبونسِ ۳۰۰ms اجماعِ رایجِ صنعت است (بازهٔ ۲۰۰–۳۰۰ms در موتورهای
 *    InstantSearch و رفتارِ گوگل): به‌قدر کافی کوتاه که «لایو» حس شود و
 *    به‌قدر کافی بلند که یک رگبارِ تایپ به یک ریکوئست فروبپاشد. ۵۰۰ms به
 *    بالا حسِ «گیرکردن» می‌دهد و زیرِ ۲۰۰ms عملاً دبونس نیست.
 *    (یادداشتِ صادقانه: جستجوی وب از این محیط ۴۰۳ خورد، پس عدد از دانشِ
 *    تثبیت‌شده می‌آید نه از مرورِ تازه — اگر کاربر ۵۰۰ms خواست، فقط همین
 *    یک ثابت عوض می‌شود.)
 *
 * عمداً خالص و بدون React است تا با `node --test` سنجیده شود و هر چهار
 * مصرف‌کننده (دو دراپ‌داون + دو صفحهٔ نتایج) از یک حقیقت بخوانند.
 */

/** کمترین طولِ عبارت (پس از trim) که جستجو را شروع می‌کند. */
export const SEARCH_MIN_LENGTH = 3;

/** مکث پس از آخرین حرف پیش از فرستادنِ ریکوئست (میلی‌ثانیه). */
export const SEARCH_DEBOUNCE_MS = 300;

/** آیا این عبارت اجازهٔ جستجو دارد؟ */
export function searchReady(raw: unknown): boolean {
  return typeof raw === "string" && raw.trim().length >= SEARCH_MIN_LENGTH;
}
