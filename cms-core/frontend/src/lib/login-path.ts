/**
 * آدرسِ صفحهٔ ورود — **یک منبعِ حقیقت**.
 *
 * ## چرا این فایل وجود دارد
 *
 * این آدرس در سه جا لازم بود و دستی نگه‌داشتنش یعنی سه بار احتمالِ اختلاف:
 *   ۱) پروکسی که کاربرِ بی‌نشست را می‌فرستد اینجا،
 *   ۲) `auth.tsx` که نشستِ منقضی را همین‌جا می‌برد،
 *   ۳) صفحهٔ عمومی که دکمهٔ «ورود به پنل» دارد.
 *
 * اولش داخل `proxy.ts` بود، ولی `proxy.ts` یک فایلِ **edge-scope** است و
 * ایمپورت کردنش به کدِ کلاینت (`auth.tsx`) یعنی کشیدن مرزِ اجرا به داخل
 * باندل. پس اینجا می‌نشیند و `proxy.ts` از اینجا می‌خواند.
 *
 * ## قرارداد
 *
 * لاگین **داخل ریشهٔ پنل** است (`/admin/login`)، نه بیرونِ آن. دلیلش این است
 * که پروکسی هر مسیر زیر ریشهٔ پنل را می‌بندد؛ اگر لاگین بیرون می‌بود، دو
 * فضای نامِ جدا برای یک کارِ واحد داشتیم و هر لینکِ دستی، یکی را لو می‌داد.
 *
 * هزینه‌اش این است که `proxy.ts` **باید** خودِ این مسیر را استثنا کند، وگرنه
 * حلقهٔ بی‌نهایت ریدایرکت می‌سازد.
 */
export const LOGIN_PATH = "/admin/login";

/**
 * آیا این مسیر **خودِ** صفحهٔ ورود است؟
 *
 * نرمال‌سازیِ انتهای `/` تا `/admin/login/` هم شناخته شود. عمداً از
 * `startsWith` استفاده نمی‌کنیم: `/admin/login-help` مسیرِ دیگری است و نباید
 * استثنا بگیرد، وگرنه یک صفحهٔ واقعیِ پنل بدون دروازه باز می‌ماند.
 */
export function isLoginPath(pathname: string): boolean {
  const normalized = pathname.replace(/\/+$/, "") || "/";

  return normalized === LOGIN_PATH;
}