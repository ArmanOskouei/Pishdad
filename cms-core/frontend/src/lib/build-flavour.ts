import { spawnSync } from 'node:child_process';

/**
 * J3 — پرچمِ «این بیلد پنلِ مرکزی ندارد».
 *
 * ## چرا لازم است
 *
 * بیلدِ مشتری و بیلدِ مرکزی **یک URL** می‌دهند و هر دو ۲۰۰ برمی‌گردانند. یعنی اگر
 * کسی نسخهٔ اشتباه را بالا بیاورد، هیچ نشانه‌ای نمی‌بیند — فقط می‌بیند «صفحهٔ
 * `/central` نیست» و حدس می‌زند.
 *
 * این پرچم می‌گوید `/central` **عمداً** نیست، نه اینکه خراب شده. تفاوتش مهم است:
 * اولی «همه‌چیز درست است»، دومی «یک چیزی اشتباه است».
 *
 * ⚠️ `server-only` است، نه `NEXT_PUBLIC_*`. دلیلش این است که این پرچم برای **لایهٔ
 * سرور** است (تشخیص در پاسخِ HTTP)، نه برای باندلِ مرورگر. اگر `NEXT_PUBLIC_`
 * بود، هر مشتری این رشته را در جاوااسکریپتش می‌دید و می‌شد از آن چیزی فهمید.
 */

/** آیا این بیلد پنلِ مرکزی ندارد؟ */
export const isClientOnlyBuild = (): boolean =>
  process.env.CMS_CLIENT_ONLY_BUILD === '1';

/** نامِ بیلد، برای لاگ و تشخیص. */
export const buildFlavour = (): 'client' | 'central' =>
  isClientOnlyBuild() ? 'client' : 'central';

/**
 * اگر بیلدِ مشتری باشد و کسی مسیرِ `/central` را بخواهد، **۴۰۴ِ با توضیح** بده
 * به‌جای `notFound` خام.
 *
 * دلیل: `notFound` یعنی «این مسیر وجود ندارد» — درست، ولی هیچ‌کس نمی‌فهمد چرا. یک
 * صفحهٔ کوتاه که می‌گوید «این نسخه عمداً پنلِ مرکزی ندارد» فرقِ «نصبِ خراب» و
 * «بیلدِ درست» را از هم جدا می‌کند.
 */
export function explainMissingCentralPanel(): {
  title: string;
  body: string;
  code: string;
} | null {
  if (!isClientOnlyBuild()) return null;

  return {
    title: 'این نسخه پنل مرکزی ندارد',
    body: 'این نصب عمداً فقط پنل مشتری را سرو می‌کند. صفحات مرکزی روی سرورِ مرکزی هستند، نه اینجا.',
    code: 'central_panel_not_in_this_build',
  };
}