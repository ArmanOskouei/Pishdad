import type { MetadataRoute } from "next";

/**
 * F5.2 — manifestِ PWA برای **پنل**.
 *
 * ## ⭐ عمداً فقط manifest + آیکون، و **بدون Service Worker**
 *
 * این تصمیم ثبت‌شده است و دلیلش معماری است، نه کم‌کاری:
 *
 *  - SW یعنی یک لایهٔ کش که برای همیشه می‌ماند. برای پنلِ مدیریت، کهنه‌شدنِ
 *    جاوااسکریپت یعنی «دکمه ذخیره کار نمی‌کند» و تشخیصش از خودِ کاربر سخت است.
 *  - هر بازنشانیِ کشِ SW یک پنجرهٔ خرابی است مگر اینکه versioning + پیامِ
 *    `skipWaiting` درست پیاده شود — که خودش یک سرویس کامل است.
 *  - «نصب روی صفحهٔ اصلی» فقط **manifest + آیکون** می‌خواهد. آنچه می‌خواهیم
 *    (پنل روی صفحهٔ اصلی، باز شدن مستقل، آیکون درست) بدون SW به دست می‌آید.
 *
 * پس: `display: standalone`، آیکون‌ها، و هیچ SW. نگهبانِ
 * `src/lib/pwa-manifest.test.ts` هم نبودِ SW را گیت می‌کند تا کسی در بازآرایی
 * اضافه‌اش نکند.
 *
 * ## چرا `start_url` ریشه است و نه `/admin`
 *
 * کاربرِ نصب‌کننده ممکن است نشست نداشته باشد؛ ریشه به صفحهٔ عمومی می‌رود و
 * `/admin` به صفحهٔ لاگین با فلش. بهتر است اولین باز شدن، سایتِ عمومی باشد.
 *
 * ⚠️ TODO(F5.2): `name`/`short_name` هنوز ثابت‌اند. بعد از
 * `GET /v1/admin/settings/site` در دسترس بودنِ `title`، این فایل باید
 * پویا شود — ولی `manifest.ts` در این پروژه static است و پویا‌کردنش یعنی
 * Route Handler دستی، که ارزشش را ندارد تا وقتی درخواستی برایش باشد.
 */

/** `as const` لازم است: بدون آن `purpose` به `string` پهن می‌شود و `tsc` ردش می‌کند. */
const ICON = (size: number) =>
  ({
    src: `/icons/icon-${size}.png`,
    sizes: `${size}x${size}`,
    type: "image/png",
    // ⚠️ فقط `any`، نه `maskable`: فایل‌های فعلی **تمام‌قاب**‌اند و در حالت
    // maskable لبه‌شان بریده می‌شود (نشان وسط می‌افتد). اعلامِ maskable روی آیکونی
    // که maskable نیست یعنی همان دروغی که `L-B7` دربارهٔ توکن‌ها ثبت کرد.
    purpose: "any",
  }) as const;

export const dynamic = "force-static";

/**
 * ⭐ **یک manifest برای کلِ اپ — و همین درست است (F5.1)**
 *
 * پنل و سایتِ عمومی یک اپ‌اند و یک مبدأ‌اند، پس مرورگر هم یک manifest
 * می‌بیند. `start_url` و `scope` هر دو `/` هستند — یعنی «نصب روی صفحهٔ
 * اصلی» **سایتِ عمومی** را باز می‌کند، نه `/admin` که بدون نشست به لاگین می‌رود.
 *
 * پس نام و توضیح باید هویتِ **سایت** را بگویند. نسخهٔ قبلی `name: "پنل مدیریت"`
 * و `short_name: "پنل"` بود: بازدیدکننده‌ای که سایت را روی صفحهٔ اصلی می‌گذاشت،
 * آیکونی با برچسبِ «پنل مدیریت» می‌دید که اصلاً به آن ربطی نداشت — همان دستِ
 * L-B7 برای توکن‌ها، اینجا برای هویت.
 *
 * ⚠️ **چرا هنوز hard-coded و از تنظیمات سایت نمی‌آید؟** چون `force-static` است
 * و همان استدلالِ TODO(F5.2) پابرجاست: `metadataRoute` خروجیِ نهایی و
 * استاتیک است، پس خواندنِ DB در آن یعنی یا Route Handler دستی با
 * `generateStaticParams`-ناپذیری، یا caching دستی. برای manifestی که در یک نصب
 * می‌ماند، یک رشتهٔ ثابتِ درست بهتر از یک رشتهٔ پویای نیم‌بند است. TODO عمداً
 * سرِ جایش ماند.
 */
export default function manifest(): MetadataRoute.Manifest {
  return {
    name: "پیشداد",
    short_name: "پیشداد",
    description: "پیشداد — وب‌سایت و محتوای فارسی",
    start_url: "/",
    scope: "/",
    display: "standalone",
    orientation: "any",
    lang: "fa",
    dir: "rtl",
    background_color: "#0b0f17",
    theme_color: "#0b0f17",
    categories: ["productivity", "business"],
    icons: [ICON(128), ICON(256), ICON(512)],
  };
}
