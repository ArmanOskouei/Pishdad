/**
 * تصمیمِ صفحهٔ ورود در لحظهٔ mount.
 *
 * ## باگ
 *
 * گزارشِ کاربر: «وقتی لاگین کردم و `/login` را باز می‌کنم، باز هم فرم ورود
 * نشان داده می‌شود.» یعنی صفحه اصلاً نمی‌پرسید «نشستِ معتبری هست؟» و فقط
 * فرم را رندر می‌کرد.
 *
 * ## چرا این تصمیم یک تابعِ خالص است
 *
 * هر سه حالت باید یک جوابِ قابل‌تست بدهند، و تستِ کامپوننت برای این سه
 * حالت سنگین است (به `AuthProvider`، روتر و تایمر نیاز دارد). ضمناً هر سه
 * حالت در یک `if` زنجیره‌ای ساده جا می‌گیرند و احتمال اشتباه در ترتیبشان
 * هست — که همان چیزی است که باگ ساخت.
 */

export type LoginGate = "wait" | "redirect" | "form";

export type LoginGateInput = {
  /** هنوز وضعیتِ نشست از سرور نرسیده است. */
  loading: boolean;
  /** کاربرِ معتبر، یا `null` وقتی نشستی نیست. */
  user: unknown;
};

/**
 * `wait` ⇒ هیچ چیزی رندر نشود (نه فرم، نه اسکلت).
 * `redirect` ⇒ به داشبورد/اشتراک برو.
 * `form` ⇒ فرم ورود را نشان بده.
 */
export function loginGate({ loading, user }: LoginGateInput): LoginGate {
  // ⚠️ ترتیب این شرط‌ها خودِ باگ است.
  //
  // اگر `user` اول چک شود، لحظهٔ اول `loading=true` و `user=null` یعنی
  // «نشستی نیست» و فرم رندر می‌شود — و مدیرِ واردشده همان یک لحظه را
  // می‌بیند. اول `loading` باید کنار برود.
  if (loading) {
    return "wait";
  }

  // ⭐ حتی اگر `loading` تمام شده و `user` هنوز `null` است، یعنی نشستی نیست.
  if (user !== null && user !== undefined) {
    return "redirect";
  }

  return "form";
}
